"""Entry point: python run.py [1 2 3 4 2f 2p 2q 2l 2a 2r 2s 2t 2w 2k | all]

Each call writes a new results/<run_id>/ folder. `all` also refreshes lab/data.js.
2f = exploratory Idea 2 follow-up (amendment 2); 2p = Idea 2 Phase 2; 2q = Idea 2 Phase 3; 2l = Gemma 3 layer 11, exploratory; 2a = artifact check; 2r = Phase 4; 2s = Phase 5; 2t = Phase 6; 2w = weight drift; 2k = volume knob, exploratory (protocols/idea2_*.md).
"""
import argparse
import json
import platform

from nightshift.common import ROOT, new_run_dir, save_json

IDEAS = {
    "1": ("trajectories", "nightshift.trajectories"),
    "2": ("dark_matter", "nightshift.dark_matter"),
    "3": ("kv_fast_weights", "nightshift.kv_fast_weights"),
    "4": ("mdl_empathy", "nightshift.mdl_empathy"),
    "2f": ("dark_matter_followup", "nightshift.dark_matter", "followup"),
    "2p": ("dark_matter_phase2", "nightshift.phase2"),
    "2q": ("dark_matter_phase3", "nightshift.phase3"),
    "2l": ("dark_matter_layer11", "nightshift.layer11"),
    "2a": ("dark_matter_artifact_check", "nightshift.layer11", "artifact_check"),
    "2r": ("dark_matter_phase4", "nightshift.phase4"),
    "2s": ("dark_matter_phase5", "nightshift.phase5"),
    "2t": ("dark_matter_phase6", "nightshift.phase6"),
    "2w": ("dark_matter_weight_drift", "nightshift.weight_drift"),
    "2k": ("dark_matter_volume_knob", "nightshift.knob"),
    "2d": ("dark_matter_knob_demo", "nightshift.knob", "demo"),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ideas", nargs="*", default=["all"])
    picked = ap.parse_args().ideas
    is_all = picked == ["all"]
    picked = ["1", "2", "3", "4"] if is_all else picked
    import importlib

    import torch

    out = new_run_dir("ideas" + "".join(picked))
    meta = {"ideas": picked, "torch": torch.__version__, "python": platform.python_version(),
            "device": torch.cuda.get_device_name(0) if torch.cuda.is_available() else "cpu"}
    save_json(out / "run_meta.json", meta)
    summary = {}
    for key in picked:
        name, module, *func = IDEAS[key]
        print(f"idea {key}: {name}")
        torch.manual_seed(0)
        summary[name] = getattr(importlib.import_module(module), func[0] if func else "run")(out)
        print("  predictions:", summary[name].get("predictions", "exploratory, none pre-registered"))
    if "2p" in picked:
        (ROOT / "lab" / "phase2.js").write_text(
            f"// Generated by run.py from results/{out.name}. Do not edit.\nwindow.PHASE2_RUN = {json.dumps(out.name)};\n"
            f"window.PHASE2 = {json.dumps(summary['dark_matter_phase2'])};\n", encoding="utf-8")
    if "2q" in picked:
        p3 = summary["dark_matter_phase3"]
        slim = {"predictions": p3["predictions"], "models": {
            n: {"A": {k: m["A"][k] for k in ("dCE_mean", "diff_thresh_minus")}, "B": m["B"], "C": m["C"]}
            for n, m in p3["models"].items() if "error" not in m}}
        (ROOT / "lab" / "phase3.js").write_text(
            f"// Generated by run.py from results/{out.name}. Do not edit.\nwindow.PHASE3_RUN = {json.dumps(out.name)};\n"
            f"window.PHASE3 = {json.dumps(slim)};\n", encoding="utf-8")
    if not is_all:
        print("wrote", out.relative_to(ROOT))
        return
    (ROOT / "lab" / "data.js").write_text(
        f"// Generated by run.py from results/{out.name}. Do not edit.\nwindow.RUN_ID = {json.dumps(out.name)};\n"
        f"window.DATA = {json.dumps(summary)};\n", encoding="utf-8")
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
